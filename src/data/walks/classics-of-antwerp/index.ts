/**
 * "Classics of Antwerp": a narrated historical walk (experience: "guide").
 *
 *   stops.ts          positions-independent facts, images and sources per stop
 *   content/<lang>.ts all text per language (content/en.ts is the master; see content/index.ts)
 *   coordinates.json  stop positions   → node scripts/generate-walking-routes.mjs classics-of-antwerp
 *   image-sources.json which images    → node scripts/download-commons-images.mjs classics-of-antwerp
 *   images.json, routes.json           generated by those scripts
 *   local-images.json  the few images that don't come from Commons (maintained by hand)
 *   audio.json         the audio guide's recordings → node scripts/generate-audio-guide.mjs classics-of-antwerp
 */

/** What an image needs besides its texts, whichever file it comes from. */
interface ImageMetadata {
  localPath: string;
  width: number;
  height: number;
  photographerOrArtist: string;
  source: string;
  sourceUrl: string;
  imageUrl: string;
  license: string;
  licenseUrl: string | null;
}

/** Commons sometimes writes "Unknown author" or "AnonymousUnknown author"; show a clean name in the visitor's language. */
function cleanArtist(artist: string, unknownLabel: string): string {
  return /^(unknown|anonymous)/i.test(artist.trim()) ? unknownLabel : artist.trim();
}

/** Credit texts in the visitor's language, for images whose maker, source or rights are not known. */
interface ImageLabels {
  unknownArtist: string;
  sourceToVerify: string;
  rightsToVerify: string;
}

/** Image metadata from images.json (Commons) or, for the few images that don't come from Commons, local-images.json. */
function findImageMetadata(id: string, labels: ImageLabels): ImageMetadata | undefined {
  const commons = imagesFile.images.find((image) => image.id === id);
  if (commons) return commons;
  const local = localImagesFile.images.find((image) => image.id === id);
  if (!local) return undefined;
  return {
    ...local,
    // Unknown source or rights are shown as such, never left blank.
    source: local.source ?? labels.sourceToVerify,
    license: local.rightsCleared && local.license ? local.license : labels.rightsToVerify,
  };
}

function buildImage(id: string, content: ClassicsContent, labels: ImageLabels): GuideImage {
  const metadata = findImageMetadata(id, labels);
  const text = content.images[id];
  if (!metadata || !text) throw new Error(`Classics of Antwerp: missing image data for "${id}"`);

  return {
    id,
    src: metadata.localPath,
    width: metadata.width,
    height: metadata.height,
    alt: text.alt,
    caption: text.caption,
    approximateYear: text.approximateYear,
    photographerOrArtist: cleanArtist(metadata.photographerOrArtist, labels.unknownArtist),
    source: metadata.source,
    sourceUrl: metadata.sourceUrl,
    imageUrl: metadata.imageUrl,
    license: metadata.license,
    licenseUrl: metadata.licenseUrl ?? undefined,
    // Modern comparison photos are stored with ids ending in "-today".
    isHistorical: !id.endsWith("-today"),
  };
}

/** Slides (or optional stories) of a stop: images from stops.ts, texts from content. */
function buildCards(
  stopId: string,
  definitions: CardDefinition[] | undefined,
  texts: Record<string, CardText> | undefined,
  content: ClassicsContent,
  labels: ImageLabels,
): GuideCard[] | undefined {
  if (!definitions) return undefined;
  return definitions.map((card) => {
    const text = texts?.[card.id];
    if (!text) throw new Error(`Classics of Antwerp: missing text for card "${card.id}" at "${stopId}"`);
    const [first, ...others] = card.imageIds.map((id) => buildImage(id, content, labels));
    return { id: card.id, ...text, image: first, images: others.length > 0 ? others : undefined };
  });
}

/** Image galleries of a stop: images from stops.ts, title and intro from content. */
function buildGalleries(
  stopId: string,
  definitions: CardDefinition[] | undefined,
  texts: Record<string, GalleryText> | undefined,
  content: ClassicsContent,
  labels: ImageLabels,
): GuideGallery[] | undefined {
  if (!definitions) return undefined;
  return definitions.map((gallery) => {
    const text = texts?.[gallery.id];
    if (!text) throw new Error(`Classics of Antwerp: missing text for gallery "${gallery.id}" at "${stopId}"`);
    return { id: gallery.id, ...text, images: gallery.imageIds.map((id) => buildImage(id, content, labels)) };
  });
}

/** Spooky's quest at a stop: where and which clue from stops.ts, the texts from content. */
function buildQuest(
  stopId: string,
  definition: QuestDefinition | undefined,
  text: QuestText | undefined,
  content: ClassicsContent,
  labels: ImageLabels,
): LocationQuest | undefined {
  if (!definition) return undefined;
  if (!text) throw new Error(`Classics of Antwerp: missing quest text for "${stopId}"`);
  const base = { title: text.title, task: text.task, clueImage: buildImage(definition.clueImageId, content, labels) };
  if (definition.type === "discovery") return { type: "discovery", ...base };
  if (!text.zoneHint || !text.revealedName) {
    throw new Error(`Classics of Antwerp: the quest at "${stopId}" needs a zoneHint and revealedName`);
  }
  return {
    type: "location",
    ...base,
    zoneHint: text.zoneHint,
    searchZone: definition.searchZone,
    arrivalRadiusMeters: definition.arrivalRadiusMeters,
    revealedName: text.revealedName,
    revealedAddress: definition.revealedAddress,
  };
}

function buildLocations(content: ClassicsContent, labels: ImageLabels): WalkLocation[] {
  return stopDefinitions.map((stop, index) => {
    const text = content.stops[stop.id];
    if (!text) throw new Error(`Classics of Antwerp: missing text for "${stop.id}"`);

    return {
      id: stop.id,
      order: index + 1,
      name: text.name,
      type: stop.type,
      address: stop.address,
      ...findPosition(coordinatesFile, stop.id),
      description: text.subtitle,
      quest: buildQuest(stop.id, stop.quest, text.quest, content, labels),
      guide: {
        subtitle: text.subtitle,
        introduction: text.introduction,
        sections: text.sections,
        didYouKnow: text.didYouKnow,
        lookAt: text.lookAt,
        images: stop.imageIds.map((id) => buildImage(id, content, labels)),
        thenNow: stop.thenNow
          ? { then: buildImage(stop.thenNow.then, content, labels), now: buildImage(stop.thenNow.now, content, labels) }
          : undefined,
        transitionToNext: text.transitionToNext,
        closing: text.closing,
        cards: buildCards(stop.id, stop.cards, text.cards, content, labels),
        moreStories: buildCards(stop.id, stop.moreStories, text.moreStories, content, labels),
        galleries: buildGalleries(stop.id, stop.galleries, text.galleries, content, labels),
        infoBoxes: text.infoBoxes,
        verification: stop.verification,
        sources: stop.sources,
      },
    };
  });
}

function buildWalk(content: ClassicsContent, locale: Locale): Walk {
  const t = createTranslator(locale);
  const routeLegs = loadRouteLegs(routesFile);
  const locations = buildLocations(content, {
    unknownArtist: t("guide.unknownArtist"),
    sourceToVerify: t("guide.sourceToVerify"),
    rightsToVerify: t("guide.rightsToVerify"),
  });

  return {
    id: "walk-classics-of-antwerp",
    slug: "classics-of-antwerp",
    title: content.walk.title,
    tagline: content.walk.tagline,
    shortDescription: content.walk.shortDescription,
    description: content.walk.description,
    city: t("common.cities.antwerp"),
    // About 80 minutes of walking plus reading and looking at 19 stops.
    estimatedDuration: { minMinutes: 175, maxMinutes: 205 },
    distanceInMeters: getMainRouteDistance("Classics of Antwerp", locations, routeLegs),
    difficulty: "easy",
    price: { amountInCents: 995, currency: "EUR" },
    coverImage: {
      src: "/images/classics/central-station/historical-1906.jpg",
      alt: content.images["central-station-1906"]?.alt ?? "",
    },
    theme: "archive",
    experience: "guide",
    languages: availableLocales(classicsContent),
    routeReveal: "all",
    team: { minPlayers: 1, maxPlayers: 1 },
    // Researched against the listed sources, but not yet reviewed by a historian.
    contentStatus: "placeholder",
    copy: content.walk.copy,
    guideIntro: content.walk.guideIntro,
    highlights: content.walk.highlights,
    howItWorksSteps: content.walk.howItWorksSteps,
    practicalInfo: content.walk.practicalInfo,
    routeLegs,
    // The audio guide: each stop and slide gets its recording in this language (when up to date).
    locations: attachAudioGuide(locations, audioFile as AudioGuideFile, locale, t),
  };
}

/** The walk with its texts in `locale` (English where a translation is missing). */
export const getClassicsWalk = cachePerLocale((locale) => buildWalk(pickContent(classicsContent, locale), locale));

/** English, e.g. for tests. */
export const classicsOfAntwerpWalk: Walk = getClassicsWalk("en");
